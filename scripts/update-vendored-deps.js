#!/usr/bin/env node
/**
 * Maintainer-only helper: refreshes the vendored native dependencies under
 * thirdparty/. Nothing in the build path calls this — both libharu and libpng
 * are checked into the repository and compiled from source, so installs and
 * builds never touch the network.
 *
 * Usage:
 *   node scripts/update-vendored-deps.js
 *   LIBHARU_VERSION=2.4.6 LIBPNG_VERSION=1.6.59 node scripts/update-vendored-deps.js
 *
 * After running, review the diff and commit thirdparty/.
 */
import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ROOT = path.resolve(__dirname, '..');
const THIRDPARTY = path.join(ROOT, 'thirdparty');
const LIBHARU_DIR = path.join(THIRDPARTY, 'libharu');
const LIBPNG_DIR = path.join(THIRDPARTY, 'libpng');
const LIBHARU_VERSION = process.env.LIBHARU_VERSION || '2.4.6';
const LIBPNG_VERSION = process.env.LIBPNG_VERSION || '1.6.59';
const LIBHARU_TARBALL = `libharu-${LIBHARU_VERSION}.tar.gz`;
const LIBPNG_TARBALL = `libpng-${LIBPNG_VERSION}.tar.gz`;
const LIBHARU_URL = `https://github.com/libharu/libharu/releases/download/v${LIBHARU_VERSION}/${LIBHARU_TARBALL}`;
const LIBHARU_FALLBACK_URL = `https://github.com/libharu/libharu/archive/refs/tags/v${LIBHARU_VERSION}.tar.gz`;
const LIBPNG_URL = `https://github.com/pnggroup/libpng/releases/download/v${LIBPNG_VERSION}/${LIBPNG_TARBALL}`;
const LIBPNG_FALLBACK_URL = `https://download.sourceforge.net/libpng/${LIBPNG_TARBALL}`;

function log(message) {
  console.log(`[update-vendored-deps] ${message}`);
}

function exists(file) {
  try {
    fs.accessSync(file);
    return true;
  } catch {
    return false;
  }
}

/**
 * The upstream tarball does not contain hpdf_config.h, so one is generated.
 * The banner must state the version that is actually on disk — reading it from
 * hpdf_version.h instead of echoing the requested tag is what keeps NOTICE and
 * the sources from drifting apart.
 */
function readLibharuVersion() {
  const headerPath = path.join(LIBHARU_DIR, 'include', 'hpdf_version.h');
  const text = fs.readFileSync(headerPath, 'utf8');
  const part = (name) => {
    const match = text.match(new RegExp(`HPDF_${name}_VERSION\\s+(\\d+)`));
    if (!match) {
      throw new Error(`Cannot read HPDF_${name}_VERSION from ${headerPath}`);
    }
    return match[1];
  };
  return `${part('MAJOR')}.${part('MINOR')}.${part('BUGFIX')}`;
}

function writeLibharuConfig() {
  const actualVersion = readLibharuVersion();
  const configPath = path.join(LIBHARU_DIR, 'include', 'hpdf_config.h');
  const configContent = `/* Vendored build config for libharu ${actualVersion} (thirdparty/libharu).
 * Generated by scripts/update-vendored-deps.js — not part of the upstream tarball.
 * Only the switches the sources actually test are set; libharu 2.4.x ships
 * include/hpdf_config.h.cmake which defines exactly these. */
#ifndef _HPDF_CONFIG_H
#define _HPDF_CONFIG_H

/* libpng is vendored under thirdparty/libpng and compiled from source. */
#define LIBHPDF_HAVE_LIBPNG 1

/* zlib comes from the platform (podspec \`s.libraries = 'z'\`, CMake \`z\`). */
#define LIBHPDF_HAVE_ZLIB 1

#endif /* _HPDF_CONFIG_H */
`;
  fs.writeFileSync(configPath, configContent, 'utf8');
  log(`Wrote ${path.relative(ROOT, configPath)} (libharu ${actualVersion})`);
  return actualVersion;
}

function readLibpngVersion() {
  const headerPath = path.join(LIBPNG_DIR, 'png.h');
  const text = fs.readFileSync(headerPath, 'utf8');
  const match = text.match(/PNG_LIBPNG_VER_STRING\s+"([^"]+)"/);
  if (!match) {
    throw new Error(`Cannot read PNG_LIBPNG_VER_STRING from ${headerPath}`);
  }
  return match[1];
}

/** libpng ships a prebuilt pnglibconf.h template; the configure step is not run here. */
function writePnglibconf() {
  const template = path.join(LIBPNG_DIR, 'scripts', 'pnglibconf.h.prebuilt');
  const dest = path.join(LIBPNG_DIR, 'pnglibconf.h');
  if (!exists(template)) {
    throw new Error(`Missing ${path.relative(ROOT, template)}`);
  }
  fs.copyFileSync(template, dest);
  log(`Copied ${path.relative(ROOT, dest)}`);
}

function assertVendoredVersion(name, requested, actual) {
  if (requested !== actual) {
    throw new Error(
      `${name}: requested ${requested} but the extracted sources report ${actual}. ` +
        'Refusing to vendor a tree that does not match the requested tag.'
    );
  }
  log(`${name} ${actual} verified against the extracted sources`);
}

function ensureIgnoreExceptions() {
  const exceptions = [
    {
      file: path.join(LIBHARU_DIR, 'include', '.gitignore'),
      line: '!hpdf_config.h',
      comment: '# Vendored build config is committed (generated, not present in the tarball).',
    },
    {
      file: path.join(LIBPNG_DIR, '.gitignore'),
      line: '!pnglibconf.h',
      comment:
        '# Vendored build config is committed (copied from scripts/pnglibconf.h.prebuilt).',
    },
  ];
  for (const { file, line, comment } of exceptions) {
    if (!exists(file)) {
      continue;
    }
    const content = fs.readFileSync(file, 'utf8');
    if (content.includes(line)) {
      continue;
    }
    fs.appendFileSync(file, `\n${comment}\n${line}\n`, 'utf8');
    log(`Re-included ${line.slice(1)} in ${path.relative(ROOT, file)}`);
  }
}

function downloadFile(url, dest) {
  const curl = 'curl -L --fail --max-time 300';
  try {
    execSync(`${curl} -o "${dest}" "${url}"`, { stdio: 'inherit' });
    return;
  } catch {
    // ignore, try wget
  }
  try {
    execSync(`wget --timeout=300 -O "${dest}" "${url}"`, { stdio: 'inherit' });
  } catch (error) {
    throw new Error(`Failed to download ${url}: ${error.message}`);
  }
}

function fetchTree({ name, version, primaryUrl, fallbackUrl, tarball, dest, marker, afterExtract }) {
  const tempDir = fs.mkdtempSync(path.join(ROOT, `.${name}-download-`));
  const tarballPath = path.join(tempDir, tarball);

  try {
    log(`Downloading ${name} v${version}...`);
    try {
      downloadFile(primaryUrl, tarballPath);
    } catch {
      log('Primary download failed, trying fallback URL...');
      downloadFile(fallbackUrl, tarballPath);
    }

    log(`Extracting ${name}...`);
    execSync(`tar -xzf "${tarballPath}" -C "${tempDir}"`, { stdio: 'inherit' });

    const extracted = fs
      .readdirSync(tempDir)
      .filter(
        (entry) =>
          entry.startsWith(name) && fs.statSync(path.join(tempDir, entry)).isDirectory()
      );
    if (extracted.length !== 1) {
      throw new Error(
        `Expected exactly one extracted ${name} directory, found: ${extracted.join(', ')}`
      );
    }

    // Swap by rename, and hold the previous tree as a backup until the new one
    // passes its version assertion. Deleting first would leave an unverified
    // checkout in place if the assertion throws.
    const backup = `${dest}.backup-${Date.now()}`;
    let replaced = false;
    let swapped = false;
    try {
      if (exists(dest)) {
        log(`Replacing existing ${path.relative(ROOT, dest)}`);
        fs.renameSync(dest, backup);
        replaced = true;
      }
      fs.renameSync(path.join(tempDir, extracted[0]), dest);
      swapped = true;

      if (!exists(marker)) {
        throw new Error(`${name} extraction did not produce ${path.relative(ROOT, marker)}`);
      }
      if (afterExtract) {
        afterExtract();
      }
    } catch (error) {
      // Roll back: drop whatever landed in place and restore the previous tree,
      // so a failed swap never leaves a .backup-<ts> tree stranded (and never
      // leaves an unverified checkout where the build expects the old one).
      if (swapped) {
        fs.rmSync(dest, { recursive: true, force: true });
      }
      if (replaced) {
        fs.renameSync(backup, dest);
        log(`Rolled back ${name} to the previous tree`);
      }
      throw error;
    }
    if (replaced) {
      fs.rmSync(backup, { recursive: true, force: true });
    }
    log(`${name} v${version} vendored into ${path.relative(ROOT, dest)}`);
  } finally {
    fs.rmSync(tempDir, { recursive: true, force: true });
  }
}

fs.mkdirSync(THIRDPARTY, { recursive: true });

fetchTree({
  name: 'libharu',
  version: LIBHARU_VERSION,
  primaryUrl: LIBHARU_URL,
  fallbackUrl: LIBHARU_FALLBACK_URL,
  tarball: LIBHARU_TARBALL,
  dest: LIBHARU_DIR,
  marker: path.join(LIBHARU_DIR, 'include', 'hpdf.h'),
  afterExtract: () => {
    const actual = writeLibharuConfig();
    assertVendoredVersion('libharu', LIBHARU_VERSION, actual);
  },
});

fetchTree({
  name: 'libpng',
  version: LIBPNG_VERSION,
  primaryUrl: LIBPNG_URL,
  fallbackUrl: LIBPNG_FALLBACK_URL,
  tarball: LIBPNG_TARBALL,
  dest: LIBPNG_DIR,
  marker: path.join(LIBPNG_DIR, 'png.h'),
  afterExtract: () => {
    writePnglibconf();
    assertVendoredVersion('libpng', LIBPNG_VERSION, readLibpngVersion());
  },
});

ensureIgnoreExceptions();
log('Done. Review the diff under thirdparty/ and commit it.');
